"""Concatenate the v2 theme CSS into one render-blocking file (fewer requests).

Run after editing any source file:  python scripts/build_v2_css.py
tests/test_theme.py fails when static/css/v2/all.css is out of date.
"""
from pathlib import Path

CSS_DIR = Path(__file__).resolve().parent.parent / "static" / "css" / "v2"
SOURCES = ("tokens.css", "base.css", "compat.css", "shell.css", "components.css", "detail.css")
OUTPUT = CSS_DIR / "all.css"


def build() -> str:
    parts = ["/* GENERATED by scripts/build_v2_css.py - edit the source files, not this one. */\n"]
    for name in SOURCES:
        parts.append(f"\n/* ==== {name} ==== */\n{(CSS_DIR / name).read_text()}\n")
    return "".join(parts)


if __name__ == "__main__":
    OUTPUT.write_text(build())
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")
